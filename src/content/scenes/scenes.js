const makeId = (sceneId, label) =>
  `${sceneId}-${label.toLowerCase().replace(/[^a-zа-я0-9]+/gi, '-')}`;

export const scenes = sceneDefinitions.map((definition, index) => ({
  ...definition,
  order: index + 1,
  presentationImage: {
    src: `/presentation-slides/${definition.imageNumber}.png`,
    alt: `Иллюстрация к слайду ${index + 1}: ${definition.title}`,
  },
  shortTitle: definition.title,
  eyebrow: 'Вебзайм · Агентная разработка',
  rendererKey: 'story',
  visual: { labels: definition.items.map((entry) => entry.label) },
  hoverItems: definition.items.map((entry) => ({
    id: makeId(definition.id, entry.label),
    ...entry,
  })),
  accessibility: {
    diagramDescription: `Схема сцены «${definition.title}» с интерактивными пояснениями каждого элемента.`,
  },
  presentation: { transition: 'expand', skippable: true },
}));
